-- Add the customer dimension to forecasts and enforce customer module access.
-- The table may already exist from the user's setup SQL.
create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  customer text not null,
  salesman text,
  sales_tag text,
  customer_type text,
  status text not null default 'Active',
  segment text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.customers enable row level security;
grant select, insert, update, delete on public.customers to authenticated;
grant usage, select on sequence public.customers_id_seq to authenticated;

alter table public.sales_forecasts
  add column if not exists customer_id bigint null
  references public.customers(id) on delete restrict;
create index if not exists sales_forecasts_customer_id_idx
  on public.sales_forecasts(customer_id);

-- A permissive policy supplies the baseline grant; restrictive policies then
-- intersect with existing policies and the saved per-user module permissions.
drop policy if exists app_customers_authenticated_base on public.customers;
create policy app_customers_authenticated_base on public.customers as permissive
  for all to authenticated using (true) with check (true);

drop policy if exists app_customers_action_select on public.customers;
create policy app_customers_action_select on public.customers as restrictive
  for select to authenticated using (
    public.has_module_permission('Customers','view')
    or public.has_module_permission('Sales Input','view')
    or public.has_module_permission('Weekly Sales','view')
    or public.has_module_permission('Approvals','view')
  );
drop policy if exists app_customers_action_insert on public.customers;
create policy app_customers_action_insert on public.customers as restrictive
  for insert to authenticated with check (public.has_module_permission('Customers','add'));
drop policy if exists app_customers_action_update on public.customers;
create policy app_customers_action_update on public.customers as restrictive
  for update to authenticated using (public.has_module_permission('Customers','edit'))
  with check (public.has_module_permission('Customers','edit'));
drop policy if exists app_customers_action_delete on public.customers;
create policy app_customers_action_delete on public.customers as restrictive
  for delete to authenticated using (public.has_module_permission('Customers','delete'));

-- Permission rows remain authoritative; role defaults apply only if no row is
-- present. These defaults match lib/authorization-rules.ts.
create or replace function public.has_module_permission(p_module text, p_action text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_role text;
  v_saved boolean;
begin
  select u.role into v_role
  from public.users u
  where u.id = auth.uid() and u.is_active is true;

  if v_role is null then return false; end if;

  if (p_module = 'Dashboard' and p_action in ('add','edit','delete'))
     or (p_module = 'Weekly Sales' and p_action in ('add','edit','delete'))
     or (p_module = 'Approvals' and p_action in ('add','delete')) then
    return false;
  end if;

  select case p_action
    when 'view' then p.can_view
    when 'add' then p.can_add
    when 'edit' then p.can_edit
    when 'delete' then p.can_delete
    else false
  end into v_saved
  from public.user_permissions p
  where p.user_id = auth.uid() and p.module = p_module;

  if found then return coalesce(v_saved, false); end if;
  if v_role = 'Admin' then return true; end if;
  if v_role = 'User' then
    return (p_module in ('Dashboard','Weekly Sales') and p_action = 'view')
      or (p_module = 'Sales Input' and p_action in ('view','add','edit'));
  elsif v_role = 'Superuser' then
    return (p_module in ('Dashboard','Sales Input','Weekly Sales','Approvals','Categories','Products','Customers','Regions','Subregions') and p_action = 'view')
      or (p_module = 'Sales Input' and p_action in ('add','edit'))
      or (p_module = 'Customers' and p_action in ('add','edit'))
      or (p_module in ('Budget','Week Locks') and p_action in ('view','add','edit'));
  elsif v_role = 'Manager' then
    return (p_module in ('Dashboard','Sales Input','Weekly Sales','Approvals','Categories','Products','Customers','Regions','Subregions','Budget','Week Locks') and p_action = 'view')
      or (p_module = 'Approvals' and p_action = 'edit');
  end if;
  return false;
end;
$$;
revoke all on function public.has_module_permission(text,text) from public;
grant execute on function public.has_module_permission(text,text) to authenticated;

-- Add default Customers permission rows without changing explicitly saved rows.
insert into public.user_permissions(user_id,module,can_view,can_add,can_edit,can_delete,is_default)
select u.id, 'Customers', u.role in ('Superuser','Manager','Admin'),
       u.role in ('Superuser','Admin'), u.role in ('Superuser','Admin'), u.role = 'Admin', true
from public.users u
where not exists (
  select 1 from public.user_permissions p
  where p.user_id = u.id and p.module = 'Customers'
);

create or replace function public.initialize_customer_permission_default()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.user_permissions(user_id,module,can_view,can_add,can_edit,can_delete,is_default)
  values(new.id, 'Customers', new.role in ('Superuser','Manager','Admin'), new.role in ('Superuser','Admin'), new.role in ('Superuser','Admin'), new.role = 'Admin', true)
  on conflict (user_id,module) do update set
    can_view = excluded.can_view,
    can_add = excluded.can_add,
    can_edit = excluded.can_edit,
    can_delete = excluded.can_delete,
    is_default = true,
    updated_at = now()
  where public.user_permissions.is_default = true;
  return new;
end;
$$;

drop trigger if exists initialize_customer_permissions_after_profile_write on public.users;
create trigger initialize_customer_permissions_after_profile_write
after insert or update of role on public.users
for each row execute function public.initialize_customer_permission_default();
