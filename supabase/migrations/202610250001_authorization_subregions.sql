-- Ensure role values are normalized whenever legacy rows are updated.
create or replace function public.normalize_user_role()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.role = 'Region Manager' then new.role := 'Manager'; end if;
  return new;
end;
$$;
drop trigger if exists normalize_user_role_before_write on public.users;
create trigger normalize_user_role_before_write
before insert or update of role on public.users
for each row execute function public.normalize_user_role();

create or replace function public.has_module_permission(p_module text, p_action text)
returns boolean language plpgsql stable security definer set search_path = '' as $$
declare v_role text; v_saved boolean;
begin
  select u.role into v_role from public.users u where u.id = auth.uid() and u.is_active is true;
  if v_role is null then return false; end if;
  if (p_module = 'Dashboard' and p_action in ('add','edit','delete'))
     or (p_module = 'Weekly Sales' and p_action in ('add','edit','delete'))
     or (p_module = 'Approvals' and p_action in ('add','delete')) then return false; end if;

  select case p_action when 'view' then p.can_view when 'add' then p.can_add
    when 'edit' then p.can_edit when 'delete' then p.can_delete else false end
    into v_saved from public.user_permissions p
    where p.user_id = auth.uid() and p.module = p_module;
  if exists (select 1 from public.user_permissions p where p.user_id = auth.uid()) then
    return coalesce(v_saved, false);
  end if;

  if v_role = 'Admin' then return true; end if;
  if v_role = 'User' then
    return (p_module = 'Dashboard' and p_action = 'view')
      or (p_module = 'Weekly Sales' and p_action = 'view')
      or (p_module = 'Sales Input' and p_action in ('view','add','edit'));
  elsif v_role = 'Superuser' then
    return (p_module in ('Dashboard','Sales Input','Weekly Sales','Approvals','Categories','Products','Regions','Subregions') and p_action = 'view')
      or (p_module in ('Budget','Week Locks') and p_action in ('view','add','edit'));
  elsif v_role = 'Manager' then
    return (p_module in ('Dashboard','Sales Input','Weekly Sales','Approvals','Categories','Products','Regions','Subregions','Budget','Week Locks') and p_action = 'view')
      or (p_module = 'Approvals' and p_action = 'edit');
  end if;
  return false;
end;
$$;

create or replace function public.can_access_data_scope(p_region_id bigint, p_subregion_id bigint, p_owner_id uuid default null)
returns boolean language plpgsql stable security definer set search_path = '' as $$
declare v_role text; v_region bigint; v_subregion bigint;
begin
  select u.role, u.region_id, u.subregion_id into v_role, v_region, v_subregion
  from public.users u where u.id = auth.uid() and u.is_active is true;
  if v_role is null then return false; end if;
  if v_role in ('Admin','Superuser') then return true; end if;
  if v_region is null or p_region_id is distinct from v_region then return false; end if;
  if v_subregion is not null and p_subregion_id is distinct from v_subregion then return false; end if;
  if v_role = 'User' and p_owner_id is not null and p_owner_id is distinct from auth.uid() then return false; end if;
  return true;
end;
$$;

create or replace function public.can_access_region(p_region_id bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.users u where u.id=auth.uid() and u.is_active is true
      and (u.role in ('Admin','Superuser') or u.region_id=p_region_id)
  );
$$;

create or replace function public.subregion_matches_region(p_subregion_id bigint, p_region_id bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select p_subregion_id is null or exists (
    select 1 from public.subregions s where s.id = p_subregion_id and s.region_id = p_region_id
  );
$$;

-- Managers with Approvals Edit may change approval metadata and status, but not the submitted
-- forecast values. This protects columns at the table boundary as well as in the page UI.
create or replace function public.guard_approval_only_forecast_updates()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if public.has_module_permission('Approvals','edit')
     and not public.has_module_permission('Sales Input','edit') then
    if (to_jsonb(new) - array['status','approved_at','approved_by','remarks','updated_at'])
       is distinct from
       (to_jsonb(old) - array['status','approved_at','approved_by','remarks','updated_at']) then
      raise exception 'Approval permission cannot change forecast values';
    end if;
    if new.status not in ('Approved','Rejected') or new.approved_by is distinct from auth.uid() then
      raise exception 'Approval updates must set an approved or rejected status by the current user';
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists guard_approval_only_forecast_updates_before_write on public.sales_forecasts;
create trigger guard_approval_only_forecast_updates_before_write
before update on public.sales_forecasts
for each row execute function public.guard_approval_only_forecast_updates();

-- Defaults initialize automatically on new profiles and are refreshed on role changes only
-- while all existing permission rows remain system defaults. Manually edited rows are retained.
create or replace function public.initialize_default_user_permissions()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_module text; v_view boolean; v_add boolean; v_edit boolean; v_delete boolean;
begin
  if tg_op = 'UPDATE' and new.role is not distinct from old.role
     and exists (select 1 from public.user_permissions p where p.user_id = new.id) then return new; end if;
  if tg_op = 'UPDATE' and exists (select 1 from public.user_permissions p where p.user_id = new.id and not p.is_default) then return new; end if;
  foreach v_module in array array['Dashboard','Sales Input','Weekly Sales','Approvals','Budget','Categories','Products','Regions','Subregions','Users','Week Locks'] loop
    v_view := false; v_add := false; v_edit := false; v_delete := false;
    if new.role = 'User' then
      v_view := v_module in ('Dashboard','Sales Input','Weekly Sales');
      v_add := v_module = 'Sales Input'; v_edit := v_module = 'Sales Input';
    elsif new.role = 'Superuser' then
      v_view := v_module in ('Dashboard','Sales Input','Weekly Sales','Approvals','Categories','Products','Regions','Subregions');
      v_view := v_view or v_module in ('Budget','Week Locks');
      v_add := v_module in ('Budget','Week Locks'); v_edit := v_module in ('Budget','Week Locks');
    elsif new.role = 'Manager' then
      v_view := v_module in ('Dashboard','Sales Input','Weekly Sales','Approvals','Budget','Categories','Products','Regions','Subregions','Week Locks');
      v_edit := v_module = 'Approvals';
    elsif new.role = 'Admin' then
      v_view := true; v_add := true; v_edit := true; v_delete := true;
    end if;
    if (v_module = 'Dashboard' and v_add) or (v_module = 'Dashboard' and v_edit) or (v_module = 'Dashboard' and v_delete)
      or (v_module = 'Weekly Sales' and (v_add or v_edit or v_delete))
      or (v_module = 'Approvals' and (v_add or v_delete)) then
      v_add := false; v_edit := false; v_delete := false;
    end if;
    insert into public.user_permissions(user_id,module,can_view,can_add,can_edit,can_delete,is_default)
    values(new.id,v_module,v_view,v_add,v_edit,v_delete,true)
    on conflict (user_id,module) do update set
      can_view=excluded.can_view, can_add=excluded.can_add, can_edit=excluded.can_edit,
      can_delete=excluded.can_delete, is_default=true, updated_at=now();
  end loop;
  return new;
end;
$$;
drop trigger if exists initialize_default_permissions_after_profile_write on public.users;
create trigger initialize_default_permissions_after_profile_write
after insert or update of role on public.users
for each row execute function public.initialize_default_user_permissions();

-- Fill defaults for existing accounts that have no saved permission rows.
do $$
declare u record;
begin
  for u in select id, role from public.users x where not exists (select 1 from public.user_permissions p where p.user_id=x.id) loop
    perform 1 from public.users where id=u.id;
    update public.users set role=role where id=u.id;
  end loop;
end;
$$;

