-- Preserve existing policy behavior while translating any role literal in public policies.
do $$
declare p record; v_sql text;
begin
  for p in select schemaname, tablename, policyname, permissive, roles, cmd, qual, with_check
    from pg_policies where schemaname='public'
      and (coalesce(qual,'') ilike '%Region Manager%' or coalesce(with_check,'') ilike '%Region Manager%')
  loop
    execute format('drop policy %I on %I.%I', p.policyname, p.schemaname, p.tablename);
    v_sql := format('create policy %I on %I.%I as %s for %s to %s',
      p.policyname, p.schemaname, p.tablename, lower(p.permissive), p.cmd,
      coalesce(nullif(array_to_string(p.roles, ','),''),'public'));
    if p.qual is not null then v_sql := v_sql || format(' using (%s)', replace(p.qual, 'Region Manager', 'Manager')); end if;
    if p.with_check is not null then v_sql := v_sql || format(' with check (%s)', replace(p.with_check, 'Region Manager', 'Manager')); end if;
    execute v_sql;
  end loop;
end;
$$;

create table if not exists public.user_permissions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  module text not null,
  can_view boolean not null default false,
  can_add boolean not null default false,
  can_edit boolean not null default false,
  can_delete boolean not null default false,
  is_default boolean not null default false,
