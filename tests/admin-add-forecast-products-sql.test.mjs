import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { PGlite } from '../node_modules/.cache/forecast-visibility-sql/node_modules/@electric-sql/pglite/dist/index.js'

test('Admin additions preserve the original owner and enforce Add plus Edit permissions atomically', async (t) => {
  const db = new PGlite()
  const admin = '00000000-0000-0000-0000-000000000001'
  const kam = '00000000-0000-0000-0000-000000000002'
  try {
    await db.exec(`
      create role authenticated; create role anon;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$ select current_setting('test.viewer',true)::uuid $$;
      create table users(id uuid primary key,full_name text,role text,position text,region_id bigint,subregion_id bigint,is_active boolean);
      insert into users values ('${admin}','Admin','Admin',null,null,null,true),('${kam}','KAM','User','KAM',1,11,true);
      create table user_permissions(user_id uuid,module text,can_view boolean);
      create type forecast_status as enum ('Draft','Pending','Endorsed','Rejected','Approved');
      create table products(id bigint primary key,category_id bigint,weight numeric,is_active boolean);
      insert into products values (10,1,1,true),(20,2,0.5,true),(30,3,2,false),(40,4,2,true);
      create table sales_forecasts(id bigint generated by default as identity(start with 100) primary key,user_id uuid,
        region_id bigint,subregion_id bigint,customer_id bigint,year int,week int,product_id bigint,category_id bigint,
        forecast numeric,volume numeric,status forecast_status,submitted_by uuid,submitted_at timestamptz,
        endorsed_by uuid,endorsed_at timestamptz,approved_by uuid,approved_at timestamptz,
        returned_by uuid,returned_at timestamptz,remarks text);
      create function has_module_permission(text,text) returns boolean language sql stable as $$ select current_setting('test.' || $2,true)='yes' $$;
      create function forecast_week_is_open(int,int) returns boolean language sql stable as $$ select current_setting('test.open',true)='yes' $$;
    `)
    for (const file of ['202611090003_audit_logs.sql','202611120006_admin_saved_forecast_actions.sql','202611120007_admin_add_customer_forecast_products.sql']) {
      await db.exec(await readFile(new URL(`../supabase/migrations/${file}`,import.meta.url),'utf8'))
    }
    async function reset(status='Draft') {
      await db.exec(`truncate sales_forecasts,audit_logs;
        select set_config('test.viewer','${admin}',false),set_config('test.view','yes',false),
          set_config('test.edit','yes',false),set_config('test.add','yes',false),set_config('test.open','yes',false);`)
      await db.query(`insert into sales_forecasts(id,user_id,region_id,subregion_id,customer_id,year,week,product_id,category_id,forecast,volume,status,returned_at,returned_by,remarks)
        values (1,$1,1,11,100,2026,46,10,1,10,10,$2::text::forecast_status,case when $2::text='Rejected' then now() end,
          case when $2::text='Rejected' then $3::uuid end,case when $2::text='Rejected' then 'Revise quantity' end)`,[kam,status,admin])
    }
    const original = status => [{id:1,product_id:10,forecast:15,original:{product_id:10,forecast:10,status}}]
    const save = (additions=[{product_id:20,forecast:12}], status='Draft') => db.query('select save_admin_customer_forecast($1::jsonb,$2::jsonb) changed',[JSON.stringify(original(status)),JSON.stringify(additions)])
    await t.test('new rows inherit KAM ownership, scope and calculated volume, with the Admin recorded in audit', async () => {
      for (const status of ['Draft','Rejected']) {
        await reset(status)
        assert.equal((await save([{product_id:20,forecast:12,user_id:admin,region_id:99,customer_id:999}],status)).rows[0].changed,2)
        const row = (await db.query('select * from sales_forecasts where product_id=20')).rows[0]
        assert.equal(row.user_id,kam)
        assert.equal(Number(row.region_id),1)
        assert.equal(Number(row.subregion_id),11)
        assert.equal(Number(row.customer_id),100)
        assert.equal(row.year,2026)
        assert.equal(row.week,46)
        assert.equal(Number(row.volume),6)
        assert.equal(Number(row.category_id),2)
        assert.equal(row.status,'Draft')
        if (status === 'Rejected') assert.ok(row.returned_at)
        const audit = (await db.query("select actor_id,actor_name from audit_logs where table_name='sales_forecasts' and action='INSERT' and record_id=$1",[String(row.id)])).rows[0]
        assert.equal(audit.actor_id,admin)
        assert.equal(audit.actor_name,'Admin')
      }
    })
    await t.test('missing Add or Edit permission blocks the entire save, not just the new row', async () => {
      for (const permission of ['add','edit','view']) {
        await reset()
        await db.query("select set_config($1,'no',false)",[`test.${permission}`])
        await assert.rejects(save(),/permission/i)
        assert.equal(Number((await db.query('select forecast from sales_forecasts where id=1')).rows[0].forecast),10)
        assert.equal((await db.query('select count(*)::int count from sales_forecasts')).rows[0].count,1)
      }
      await reset()
      await db.exec("select set_config('test.add','no',false)")
      assert.equal((await save([])).rows[0].changed,1)
    })
    await t.test('locked weeks and pending, endorsed or approved records block additions', async () => {
      for (const status of ['Pending','Endorsed','Approved']) {
        await reset(status)
        await assert.rejects(save(undefined,status),/Only draft or returned/)
      }
      await reset()
      await db.exec("select set_config('test.open','no',false)")
      await assert.rejects(save(),/locked/)
      await reset()
      await db.exec(`select set_config('test.viewer','${kam}',false)`)
      await assert.rejects(save(),/active Admin/)
    })
    await t.test('duplicates, invalid quantities and inactive products roll back every row', async () => {
      const invalid = [
        [{product_id:10,forecast:1}],
        [{product_id:20,forecast:1},{product_id:20,forecast:2}],
        [{product_id:30,forecast:1}],
        [{product_id:20,forecast:-1}],
        [{product_id:20,forecast:'NaN'}],
        [{product_id:20,forecast:1},{product_id:999,forecast:1}],
      ]
      for (const rows of invalid) {
        await reset()
        await assert.rejects(save(rows),/already has|active product|valid nonnegative/)
        assert.equal(Number((await db.query('select forecast from sales_forecasts where id=1')).rows[0].forecast),10)
        assert.equal((await db.query('select count(*)::int count from sales_forecasts')).rows[0].count,1)
      }
    })
  } finally { await db.close() }
})
